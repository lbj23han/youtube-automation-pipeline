AUDIO_DIR.mkdir(parents=True, exist_ok=True)


# ── 청크 길이 측정 ───────────────────────────────────────────────────────────
def _get_duration(path: Path) -> float:
    r = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "default=noprint_wrappers=1:nokey=1", str(path)],
        capture_output=True, text=True, check=True,
    )
    return float(r.stdout.strip())


# ── VoiceVox 서버 체크 ────────────────────────────────────────────────────────
def check_server():
    try:
        urllib.request.urlopen(f"{VVOX_URL}/version", timeout=3)
        return True
    except Exception:
        return False


# ── TTS (한 청크) ─────────────────────────────────────────────────────────────
def synthesize(text: str, out_wav: Path, *, final_chunk: bool = False):
    # 1) audio_query (오독 교정 텍스트 사용, 자막용 원문과 분리)
    tts_text = _apply_tts_corrections(text)
    params = urllib.parse.urlencode({"text": tts_text, "speaker": SPEAKER_ID})
    req = urllib.request.Request(
        f"{VVOX_URL}/audio_query?{params}", method="POST",
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=60) as resp:
        query = json.loads(resp.read())

    # 파라미터 덮어쓰기
    query["speedScale"]      = SPEED_SCALE
    query["pitchScale"]      = PITCH_SCALE
    query["intonationScale"] = INTONATION
    if final_chunk:
        # 마지막 음절이 엔진의 후행 여백 경계에 걸리지 않게 최종 청크만 늘린다.
        query["postPhonemeLength"] = max(float(query.get("postPhonemeLength", 0.0)), 0.8)

    # 2) synthesis
    body = json.dumps(query).encode()
    params2 = urllib.parse.urlencode({"speaker": SPEAKER_ID})
    req2 = urllib.request.Request(
        f"{VVOX_URL}/synthesis?{params2}", data=body, method="POST",
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req2, timeout=120) as resp2:
        out_wav.write_bytes(resp2.read())


def _write_silence_wav(template_wav: Path, out_wav: Path, duration: float):
    """앞 청크와 동일한 WAV 형식으로 정확한 길이의 무음을 만든다."""
    with wave.open(str(template_wav), "rb") as src:
        channels = src.getnchannels()
        sample_width = src.getsampwidth()
        frame_rate = src.getframerate()

    frame_count = round(frame_rate * duration)
    silent_frame = b"\x00" * channels * sample_width
    with wave.open(str(out_wav), "wb") as dst:
        dst.setnchannels(channels)
        dst.setsampwidth(sample_width)
        dst.setframerate(frame_rate)
        dst.writeframes(silent_frame * frame_count)


# ── 스크립트 → 청크 분리 ──────────────────────────────────────────────────────
def _split_spoken_text(text: str) -> list[str]:
    paragraphs = re.split(r'\n\s*\n', text)
    sentences = []
    for para in paragraphs:
        parts = re.split(r'(?<=[。！？\n])', para)
        sentences.extend(s.strip() for s in parts if s.strip())

    chunks, current = [], ""
    for s in sentences:
        if len(current) + len(s) > CHUNK_LIMIT:
            if current:
                chunks.append(current.strip())
            current = s
        else:
            current += s
    if current.strip():
        chunks.append(current.strip())
    return chunks


def split_script(path: Path) -> list[str]:
    text = path.read_text(encoding="utf-8")
    sections = text.split(PAUSE_MARKER)
    chunks = []
    for i, section in enumerate(sections):
        chunks.extend(_split_spoken_text(section))
        if i < len(sections) - 1:
            chunks.append(PAUSE_MARKER)
    return chunks


# ── main ──────────────────────────────────────────────────────────────────────
def main():
    if not check_server():
        print("❌ VoiceVox 엔진이 실행되지 않았어요.")
        print()
        print("  Docker 방식 (터미널 새 탭에서 실행):")
        print("    docker run --rm -p 50021:50021 voicevox/voicevox_engine:cpu-ubuntu20.04-latest")
        print()
        print("  앱 방식:")
        print("    https://voicevox.hiroshiba.jp/ → VOICEVOX 다운로드 후 실행")
        return

    chunks = split_script(SCRIPT)
    spoken_positions = [i for i, chunk in enumerate(chunks, 1) if chunk != PAUSE_MARKER]
    if not spoken_positions:
        print("❌ 읽을 문장이 없어요.")
        sys.exit(1)
    final_spoken_position = spoken_positions[-1]
    print(
        f"화자 ID: {SPEAKER_ID} | 음성 청크: {len(spoken_positions)}개 | "
        f"무음: {len(chunks) - len(spoken_positions)}개 | 속도: {SPEED_SCALE}"
    )

    chunk_paths, timing_data = [], []
    cursor = 0.0
    for i, chunk in enumerate(chunks, 1):
        wav = AUDIO_DIR / f"vvox_chunk_{i:03d}.wav"
        if chunk == PAUSE_MARKER:
            if not chunk_paths:
                print("❌ 스크립트 맨 앞에는 무음 기호를 넣을 수 없어요.")
                sys.exit(1)
            _write_silence_wav(Path(chunk_paths[-1]), wav, PAUSE_SECONDS)
            dur = _get_duration(wav)
            cursor += dur
            chunk_paths.append(str(wav))
            print(f"  [{i}/{len(chunks)}] 무음 {dur:.3f}초")
            continue

        print(f"  [{i}/{len(chunks)}] {len(chunk)}자...", end=" ", flush=True)
        try:
            synthesize(chunk, wav, final_chunk=(i == final_spoken_position))
            dur = _get_duration(wav)
            timing_data.append({"text": chunk, "start": round(cursor, 3), "end": round(cursor + dur, 3)})
            cursor += dur
            chunk_paths.append(str(wav))
            print("완료")
        except Exception as e:
            print(f"❌ {e}")
            wav.unlink(missing_ok=True)
            for p in chunk_paths:
                Path(p).unlink(missing_ok=True)
            print("❌ 청크 누락을 막기 위해 보이스오버 생성을 중단합니다.")
            sys.exit(1)

    if len(chunk_paths) != len(chunks):
        print("❌ 생성된 청크 수가 원본과 다릅니다.")
        sys.exit(1)

    if len(chunk_paths) == 1:
        subprocess.run(
            ["ffmpeg", "-y", "-i", chunk_paths[0], "-q:a", "2", str(OUT)],
            capture_output=True, check=True,
        )
        Path(chunk_paths[0]).unlink(missing_ok=True)
    else:
        list_file = AUDIO_DIR / "vvox_chunks.txt"
        list_file.write_text(
            "\n".join(f"file '{Path(p).resolve()}'" for p in chunk_paths),
            encoding="utf-8",
        )
        subprocess.run(
            ["ffmpeg", "-y", "-f", "concat", "-safe", "0",
             "-i", str(list_file), "-q:a", "2", str(OUT)],
            capture_output=True, check=True,
        )
        list_file.unlink(missing_ok=True)
        for p in chunk_paths:
            Path(p).unlink(missing_ok=True)

    # 최종 MP3 인코더 패딩까지 포함한 실제 길이에 자막 타임라인을 맞춘다.
    actual_duration = _get_duration(OUT)
    if cursor > 0 and abs(actual_duration - cursor) > 0.05:
        timing_scale = actual_duration / cursor
        for segment in timing_data:
            segment["start"] = round(segment["start"] * timing_scale, 3)
            segment["end"] = round(segment["end"] * timing_scale, 3)

    TIMING_FILE = AUDIO_DIR / "chunks_timing.json"
    TIMING_FILE.write_text(json.dumps(timing_data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\n✅ {OUT}")
    print(f"✅ {TIMING_FILE}")


if __name__ == "__main__":
    main()
